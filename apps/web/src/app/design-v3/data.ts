function ev(
  source: string,
  channel: OriginChannel,
  title: string,
  quote: string,
  publishedAt: string,
  slug: string,
): Evidence {
  return {
    source,
    channel,
    title,
    quote,
    publishedAt,
    url: `https://example.test/${slug}`,
    rights: RIGHTS,
  };
}

